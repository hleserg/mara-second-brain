#!/usr/bin/env python3
"""Регрессионный корпус извлечения (Т5.5, ТЗ §17.4 п.3).

§17.4 требует, чтобы извлечение различало просьбу и обещание, owner и
requester «на regression corpus». Корпус — синтетические разговоры в
`tests/corpus/extraction/*.json`: аудио в git не кладём (§7.3, §18), живых
расшифровок тоже — только придуманные реплики вымышленных людей.

Случай — сегменты расшифровки в той же форме, что у `call_asr`, золотая
разметка и записанный ответ модели:

    {"id", "about", "occurred",
     "segments": [{"segment_id": "s0001", "start_ms", "end_ms", "text"}],
     "gold": {"requests": [{"ключ": ["смет"], "requester": "Анна",
                            "due_at": "2026-09-04"}],
              "commitments": [{"ключ": [...], "promised_to": "...", "due_at": null}],
              "не_задача": [["покрас"]]},
     "recorded": {"model", "prompt_version", "rules_version", "response",
                  "ожидаемо": {счёт этого ответа}},
     "живой": {то же — ответ настоящей модели, после `--live --record`}}

Пункт узнаётся по `ключ` — каждый кусочек должен начинать слово в `action`
(без регистра, ё = е: локальные модели ё теряют); кусочек может быть
списком вариантов — тогда хватит любого. `due_at`, если задан в золоте (и
`null` тоже), сверяется; кто — `requester` у просьбы, `promised_to` у
обещания, по началу строки без регистра («Анна» узнаёт «Анна Петрова»);
имя в золоте — только то, что прозвучало в разговоре: модели больше
ничего не дают. `не_задача` — то, что задачей
стать не должно: мысль вслух, обещание собеседника, смена договорённости;
это пояснение для читателя корпуса — задача, которую золото списков не
узнало, и так считается `лишнее`.

Счёт идёт по `requests` и `commitments` после `call_extract.normalize`, то
есть вместе с порогами, отсевом evidence и разбором срока:

- `верно` — задача (`disposition: task`) в своём списке, узнанная золотом;
- `перепутано` — задача, узнанная золотом другого списка (просьба ↔ обещание);
- `лишнее` — задача, которую золото не узнало (в том числе `не_задача`),
  и второй пункт на то же золото: дубль точность не поднимает;
- `на_ревью` — золото узнано только пунктом `needs-review`;
- `пропущено` — золото не узнано ничем;
- `кто_не_тот`, `срок_не_тот` — среди `верно`.

Точность — `верно / (верно + перепутано + лишнее)`: цель Т5.4 — точность, а
не полнота.

Режимы:

    python3 scripts/extract_eval.py --replay      # записанные ответы, в гейте
    python3 scripts/extract_eval.py --live        # облачная модель (OPENROUTER_API_KEY), на doctor
    python3 scripts/extract_eval.py --live --record   # и записать ответы в корпус

`--replay` — регресс правил: записанный ответ проходит нынешний `normalize`, и
счёт сравнивается с `ожидаемо`. Разошлось — правила изменили исход; это
либо ошибка, либо повод поднять `RULES_VERSION` и перезаписать `ожидаемо`.
`recorded` — синтетика (`model: synthetic`) с нарочными ошибками модели: она
проверяет счёт и правила, а не модель, и `--record` её не трогает. Ответ
настоящей модели `--live --record` кладёт рядом, в `живой`, — и `--replay`
сверяет оба. Запись идёт, только если ответили все случаи: корпус не
остаётся переписанным наполовину. Перед коммитом живых ответов — глазами:
модель пишет в `response` имена из промпта.
"""
import argparse
import glob
import json
import os
import re
import sys
from datetime import date

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import call_extract as ce

КОРПУС = os.path.join(HERE, "..", "tests", "corpus", "extraction")
СПИСКИ = ("requests", "commitments")
КТО = {"requests": "requester", "commitments": "promised_to"}
СЧЁТ = ("верно", "перепутано", "лишнее", "на_ревью", "пропущено",
        "кто_не_тот", "срок_не_тот")


def случаи(каталог=КОРПУС):
    """Случаи корпуса по имени файла: `[(путь, случай)]`."""
    out = []
    for p in sorted(glob.glob(os.path.join(каталог, "*.json"))):
        with open(p, encoding="utf-8") as fh:
            out.append((p, json.load(fh)))
    return out


def _текст(s):
    return str(s or "").lower().replace("ё", "е")


def _есть(кусочек, текст):
    варианты = кусочек if isinstance(кусочек, list) else [кусочек]
    return any(re.search(r"(?<!\w)" + re.escape(_текст(в)), текст) for в in варианты)


def узнаёт(золото, пункт):
    """Каждый кусочек `ключ` начинает слово в `action` пункта (ё = е);
    кусочек-список — любой из вариантов."""
    текст = _текст(пункт.get("action") or пункт.get("new_state"))
    return all(_есть(к, текст) for к in золото["ключ"])


def тот_же(золото_кто, кто):
    """«Анна» узнаёт «Анна Петрова»; пустое в золоте — не сверяется."""
    if not золото_кто:
        return True
    return _текст(кто).strip().startswith(_текст(золото_кто).strip())


def согласие(пункт, з, кто_поле):
    """Сколько деталей пункта сходится с золотом: человек и срок (0–2)."""
    return (int(тот_же(з.get(кто_поле), пункт.get(кто_поле)))
            + int("due_at" not in з or пункт.get("due_at") == з["due_at"]))


def сопоставить(пункты, золото, кто_поле=None):
    """Пункт ↔ золото один к одному: сначала наибольшее число пар, при
    равенстве — наибольшая суммарная узость золота (кусочков ключа).
    Жадное «первое подходящее» отдавало широкое золото пункту, которому
    годилось и узкое, и правильный ответ считался ошибкой; обход в глубину
    от узкого к широкому не гарантирует самой узкой из равных по числу пар
    (Codex по #158, круги 1–2). Дальше при равенстве — больше совпавших
    деталей (`согласие`, если задан `кто_поле`): две просьбы с одним ключом
    и разными людьми, выданные в обратном порядке, не должны лечь крест-
    накрест (круг 4). Списки одного звонка — единицы пунктов, и
    полный перебор с отсечением по совместимости дешевле любого хитрого
    алгоритма. Возвращает `{номер пункта: номер золота}`."""
    годится = [[з for з in range(len(золото)) if узнаёт(золото[з], пункты[п])]
               for п in range(len(пункты))]
    узость = [len(з["ключ"]) for з in золото]
    лад = [[согласие(пункты[п], золото[з], кто_поле) if кто_поле else 0
            for з in range(len(золото))] for п in range(len(пункты))]
    лучшее = [(0, 0, 0), {}]

    def обход(п, занято, пары, счёт):
        if п == len(пункты):
            if счёт > лучшее[0]:
                лучшее[:] = [счёт, dict(пары)]
            return
        for з in годится[п]:
            if з not in занято:
                занято.add(з)
                пары[п] = з
                обход(п + 1, занято, пары, (счёт[0] + 1, счёт[1] + узость[з],
                                            счёт[2] + лад[п][з]))
                del пары[п]
                занято.discard(з)
        обход(п + 1, занято, пары, счёт)
    обход(0, set(), {}, (0, 0, 0))
    return лучшее[1]


def оценить(случай, raw):
    """Ответ модели → счёт случая (словарь `СЧЁТ`)."""
    if not isinstance(raw, dict):
        raise ValueError("ответ модели не объект: %s" % type(raw).__name__)
    out = ce.normalize(raw, случай["occurred"], ce.сегменты_из(случай["segments"]))
    золото = случай.get("gold") or {}
    счёт = dict.fromkeys(СЧЁТ, 0)
    узнанные = set()                      # (список, номер золота)
    for список in СПИСКИ:
        чужой = СПИСКИ[1 - СПИСКИ.index(список)]
        задачи = [п for п in out.get(список) or [] if п.get("disposition") == "task"]
        своё = золото.get(список) or []
        пары = сопоставить(задачи, своё, КТО[список])
        for номер, пункт in enumerate(задачи):
            if номер in пары:
                з = своё[пары[номер]]
                узнанные.add((список, пары[номер]))
                счёт["верно"] += 1
                if not тот_же(з.get(КТО[список]), пункт.get(КТО[список])):
                    счёт["кто_не_тот"] += 1
                if "due_at" in з and пункт.get("due_at") != з["due_at"]:
                    счёт["срок_не_тот"] += 1
            elif any(узнаёт(з, пункт) for з in своё):
                счёт["лишнее"] += 1        # дубль уже узнанного
            elif any(узнаёт(з, пункт) for з in золото.get(чужой) or []):
                счёт["перепутано"] += 1
            else:
                счёт["лишнее"] += 1
    # Неузнанное задачами золото — с пунктами ревью тем же правилом один к
    # одному: один пункт ревью не закрывает два золота (Codex по #158,
    # круг 3), и пункт ревью из чужого списка тоже ждёт проверки, а не
    # пропал (круг 5)
    остаток = [золото[с][i] for с in СПИСКИ for i in range(len(золото.get(с) or []))
               if (с, i) not in узнанные]
    ревью = [п for с in СПИСКИ for п in out.get(с) or []
             if п.get("disposition") == "needs-review"]
    пары = сопоставить(ревью, остаток)
    счёт["на_ревью"] += len(пары)
    счёт["пропущено"] += len(остаток) - len(пары)
    return счёт


def итог(счета):
    """Сумма счетов и точность (None, если задач не было вовсе)."""
    сумма = dict.fromkeys(СЧЁТ, 0)
    for с in счета:
        for k in СЧЁТ:
            сумма[k] += с.get(k, 0)
    задач = сумма["верно"] + сумма["перепутано"] + сумма["лишнее"]
    сумма["точность"] = round(сумма["верно"] / задач, 3) if задач else None
    return сумма


def replay(каталог=КОРПУС, ключ="recorded"):
    """Записанные ответы через нынешние правила. Возвращает
    `(итог, расхождения)`; расхождение — `(id, ожидаемо, вышло)`. `ключ` —
    `recorded` (синтетика) или `живой` (ответ модели, где он записан)."""
    счета, расхождения = [], []
    for _, с in случаи(каталог):
        rec = с.get(ключ)
        if rec is None:
            continue
        вышло = оценить(с, rec["response"])
        счета.append(вышло)
        if вышло != rec["ожидаемо"]:
            расхождения.append((с["id"], rec["ожидаемо"], вышло))
    return итог(счета), расхождения


def _без_имени(raw):
    """Г7: в промпте живой модели — имя владельца (`MARA_OWNER_NAME`), и
    модель может повторить его в ответе, а ответ ложится в отслеживаемый
    корпус. Имя и его падежные формы (основа без последней гласной)
    заменяются словом «владелец» до счёта: что записано, то и посчитано.
    Синтетическое золото имени владельца не знает, счёт от замены не
    меняется."""
    import vault_common
    имя = vault_common.имя_владельца()
    if not имя:
        return raw
    основа = имя[:-1] if len(имя) > 3 and имя[-1].lower() in "аяоеёиыьй" else имя
    текст = re.sub(r"(?<!\w)%s\w*" % re.escape(основа), "владелец",
                   json.dumps(raw, ensure_ascii=False), flags=re.I)
    return json.loads(текст)


def live(каталог=КОРПУС, записать=False, спросить=None):
    """Каждый случай — модели, счёт по золоту. Случай, на котором модель
    упала или ответила не объектом, — `ошибка` в итоге, остальные идут
    дальше. `записать` — ответы и их счёт ложатся в `живой` каждого случая
    (синтетика `recorded` не трогается), и только если ошибок не было.
    `спросить` — подмена `ce.ask_model` для тестов."""
    спросить = спросить or ce.ask_model
    счета, ответы, ошибки = [], [], 0
    for путь, с in случаи(каталог):
        try:
            raw = _без_имени(спросить(ce.transcript_text(с["segments"])))
            счёт = оценить(с, raw)
        except Exception as e:
            ошибки += 1
            print("%-28s ошибка: %s" % (с["id"], type(e).__name__))
            continue
        счета.append(счёт)
        ответы.append((путь, с, raw, счёт))
        print("%-28s %s" % (с["id"], " ".join("%s=%d" % (k, счёт[k]) for k in СЧЁТ if счёт[k])))
    сумма = итог(счета)
    сумма["ошибка"] = ошибки
    if записать and not ошибки:
        for путь, с, raw, счёт in ответы:
            с["живой"] = {"model": ce.MODEL, "prompt_version": ce.PROMPT_VERSION,
                          "rules_version": ce.RULES_VERSION,
                          "owner_named": ce.конфигурация()["owner_named"],
                          "date": date.today().isoformat(),
                          "response": raw, "ожидаемо": счёт}
            with open(путь, "w", encoding="utf-8") as fh:
                json.dump(с, fh, ensure_ascii=False, indent=1)
                fh.write("\n")
    elif записать:
        print("корпус не записан: ошибок %d" % ошибки, file=sys.stderr)
    return сумма


def self_check():
    случай = {"id": "проба", "occurred": "2026-09-02T14:05:00+03:00",
              "segments": [{"segment_id": "s0001", "start_ms": 0, "end_ms": 1000,
                            "text": "пришли смету до пятницы"}],
              "gold": {"requests": [{"ключ": ["смет"], "requester": "Анна",
                                     "due_at": "2026-09-04"}],
                       "не_задача": [["покрас"]]}}
    ev = [{"segment": "s0001"}]
    raw = {"requests": [{"action": "прислать смету", "requester": "Анна Петрова",
                         "explicit": True, "deadline_phrase": "до пятницы",
                         "confidence": 0.95, "evidence": ev}],
           "commitments": [{"action": "покрасить стены", "explicit": True,
                            "deadline_phrase": "", "confidence": 0.9, "evidence": ev}]}
    с = оценить(случай, raw)
    assert (с["верно"], с["лишнее"], с["кто_не_тот"], с["срок_не_тот"]) == (1, 1, 0, 0), с
    raw["requests"][0]["confidence"] = 0.7
    с = оценить(случай, raw)
    assert (с["верно"], с["на_ревью"]) == (0, 1), с
    assert итог([{"верно": 3, "лишнее": 1}])["точность"] == 0.75
    сумма, расхождения = replay()
    assert not расхождения, расхождения
    print("extract_eval self-check: ок, случаев %d, точность записанных %s"
          % (len(случаи()), сумма["точность"]))
    return 0


def main():
    ap = argparse.ArgumentParser(description="регрессионный корпус извлечения (Т5.5)")
    ap.add_argument("--corpus", default=КОРПУС)
    ap.add_argument("--replay", action="store_true",
                    help="записанные ответы через нынешние правила")
    ap.add_argument("--live", action="store_true", help="спросить модель (OPENROUTER_API_KEY)")
    ap.add_argument("--record", action="store_true",
                    help="с --live: записать ответы и счёт в корпус")
    ap.add_argument("--self-check", action="store_true", dest="self_check")
    a = ap.parse_args()
    if a.self_check:
        return self_check()
    if a.record and not a.live:
        ap.error("--record только вместе с --live")
    if a.live:
        сумма = live(a.corpus, a.record)
        print(json.dumps(сумма, ensure_ascii=False, sort_keys=True))
        return 1 if сумма["ошибка"] else 0
    сумма, расхождения = replay(a.corpus)
    расхождения += replay(a.corpus, "живой")[1]
    for id_, ждали, вышло in расхождения:
        print("%s: ждали %s, вышло %s" % (id_, json.dumps(ждали, ensure_ascii=False),
                                          json.dumps(вышло, ensure_ascii=False)),
              file=sys.stderr)
    print(json.dumps(сумма, ensure_ascii=False, sort_keys=True))
    return 1 if расхождения else 0


if __name__ == "__main__":
    raise SystemExit(main())
