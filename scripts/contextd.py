class Handler(BaseHTTPRequestHandler):
    server_version = "contextd/1"
    protocol_version = "HTTP/1.1"

    # база одна на процесс, но соединение на поток: sqlite не любит делиться
    def con(self):
        if not hasattr(self.server, "_local"):
            self.server._local = threading.local()
        if not hasattr(self.server._local, "con"):
            self.server._local.con = mi.connect(self.server.root)
        return self.server._local.con

    timeout = 60                     # зависшая заливка иначе держит поток вечно

    def log_message(self, fmt, *args):
        pass                                  # свой лог, санитарный

    def say(self, code, obj, ctype="application/json", closing=False,
            ещё=None, поля=None):
        if code >= 400:
            # Через `say` проходят все отказы без исключения, и это
            # единственное место, где их видно разом. Раньше строку писали
            # руками у четырёх кодов, а прочие 400/403/404 не оставляли следа
            # вообще — при том что на телефоне они терминальны (`Core.kt:137`,
            # `:146`): событие пропадало совсем и молча (#30). Печатаем до
            # ответа: на оборванном соединении `write` бросит, и лог тогда
            # потерял бы ровно тот отказ, ради которого его читают.
            print(log_line(self.command,
                           urllib.parse.urlparse(self.path).path,
                           code, поля, клиент(self)), flush=True)
            # Тот же довод и для счётчика: в логе отказ виден поштучно и
            # человеку, в `/metrics` — числом и мониторингу. Раньше 401 и 413
            # снаружи выглядели одинаково, тишиной, а чинятся по-разному:
            # первый перевыпуском пары, второй на телефоне (#71).
            with _замок:
                _отказы[code] = _отказы.get(code, 0) + 1
        body = (obj if isinstance(obj, (bytes, bytearray)) else
                json.dumps(obj, ensure_ascii=False).encode("utf-8")
                if ctype == "application/json" else obj.encode("utf-8"))
        self.send_response(code)
        if closing:
            self.send_header("Connection", "close")
        for k, v in (ещё or {}).items():
            self.send_header(k, v)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def отлуп(self, code, текст, ещё=None):
        """Ответ на тело, которое мы отказались читать.

        Клиент в этот момент ещё шлёт: закроем соединение молча — он увидит
        broken pipe вместо кода. Поэтому вычитываем в никуда, но не больше
        СЛИВ: отказ читать полгигабайта — половина смысла лимита.

        Порядок — ответ, потом слив. Клиент узнаёт код сразу, а не после
        восьми мегабайт, и всё равно не остаётся без ответа: соединение
        закрывается только когда слив кончился. `say` сокет не закрывает,
        закрывает возврат из обработчика.
        """
        # `ожидает_тела` — отказ на `Expect: 100-continue`. Ждать `100` клиент
        # не обязан: заголовок спрашивает разрешения, но транспорт вправе
        # полить тело сразу. Поэтому сливаем и здесь — иначе закрытое с
        # непрочитанным телом соединение покажет ему broken pipe, ровно то, от
        # чего чинили #30. Разница одна: короткий таймаут. Дождавшийся не
        # пришлёт ни байта, и обычный слив упёрся бы в `timeout = 60`, держа
        # поток ровно столько, сколько предел и заводился экономить.
        #
        # Флаг одноразовый: снимается и здесь, и в `finally` у
        # `handle_expect_100`. Залипни он — короткий таймаут достался бы
        # обычному отказу на том же keep-alive соединении и оборвал бы слив на
        # первой же паузе медленного клиента, то есть вернул бы #30. Чтобы это
        # случилось, сломать надо оба снятия сразу.
        ждём = getattr(self, "ожидает_тела", False)
        self.ожидает_тела = False
        self.close_connection = True
        ответ = self.say(code, {"error": текст}, closing=True, ещё=ещё)
        if ждём:
            self.connection.settimeout(ТИШИНА)
        try:
            слить(self.rfile, min(длина(self) or 0, СЛИВ), Никуда())
        except Exception:
            # Клиент объявил длину и замолчал — или, прочитав код, закрылся
            # сам. `слить` упирается в таймаут либо в EOF и бросает; ответ к
            # этому времени уже ушёл, так что терять нечего.
            pass
        return ответ

    def authed(self, path):
        if path in OPEN_PATHS:
            return True
        if path == "/metrics" and self.client_address[0] in LOOPBACK:
            return True
        adr = клиент(self)
        # Считаем попытку до проверки токена, но верный токен всё равно
        # проходит и обнуляет счёт: за одним NAT с подбирающим может сидеть
        # телефон владельца, и запирать его заодно — это отказ в обслуживании
        # своими руками.
        ждать = под_замком(adr, False)
        dev = device_of(self.con(), self.headers.get("Authorization"))
        if dev:
            под_замком(adr, True)
            # Токен узла живёт на чужой машине (bigpc, GTR) и годится только
            # для сердцебиения: утёкший, он не должен читать пакет
            # обязательств (`/v1/context/bootstrap`) или слать события. И
            # наоборот: сердцебиение — только от узла, иначе телефон мог бы
            # отчитаться за bigpc.
            if (узел_устройства(self.con(), dev) is None) == (path == ПУТЬ_СЕРДЦА):
                self.отлуп(403, "сердцебиение — только токеном узла (--pair-node), "
                                "и токен узла годится только для него")
                return False
            return True
        if ждать:
            self.отлуп(429, "слишком много попыток", {"Retry-After": str(ждать)})
            return False
        # тело неопознанного запроса тоже вычитываем: иначе его хвост уедет в
        # следующий запрос на том же соединении и сервер ответит 400 на мусор
        self.отлуп(401, "устройство не опознано")
        return False

    def do_GET(self):
        p = urllib.parse.urlparse(self.path)
        if not self.authed(p.path):
            return
        con = self.con()
        if p.path == "/healthz":
            return self.say(200, health(con, self.server.root,
                                        full=self.client_address[0] in LOOPBACK))
        if p.path == "/metrics":
            return self.say(200, metrics(con, self.server.root, self.server.vault),
                            ctype="text/plain; version=0.0.4")
        if p.path.startswith("/v1/jobs/"):
            row = con.execute("select id,kind,state,attempts,next_at,last_error "
                              "from jobs where id=?", (p.path[9:],)).fetchone()
            if not row:
                return self.say(404, {"error": "нет такой работы"})
            # проверка на петлю — по адресу сокета, как у /metrics: заголовком
            # петлёй не притвориться (см. `клиент`). Обманул бы прокси на самом
            # doctor; такого нет — KeenDNS живёт на роутере, отдельной коробкой
            петля = self.client_address[0] in LOOPBACK
            return self.say(200, job_view(row, петля))
        if p.path == "/v1/context/bootstrap":
            if not можно_читать(con, device_of(con, self.headers.get("Authorization"))):
                return self.say(403, {"error": ОТКАЗ_ЧТЕНИЯ})
            # след чтения (Т6.4): плагин ходит не чаще раза в TTL (60 с), и
            # строка — единственный признак, что пакет читает чужой токен
            print(log_line("GET", p.path, 200, None, клиент(self)), flush=True)
            return self.say(200, bootstrap(con, self.server.vault))
        return self.say(404, {"error": "нет такого пути"})

    def аудио(self, con, p, n, dev):
        """Тело заливки. Вынесено из `do_POST` ради `finally` вокруг места.

        `dev` приходит готовым: место под заливку уже искали по нему, и второй
        поход в `devices` за тем же ответом здесь лишний.
        """
        eid = (urllib.parse.parse_qs(p.query).get("event") or [""])[0]
        # Дозагрузка — продолжение уже принятого события, и allowlist
        # обязан её накрывать: ADR-0009 прямо ждёт, что телефон с пустым
        # списком получит отлуп на первом же `audio`. Тело здесь ещё не
        # вычитано, поэтому отказ идёт через `отлуп`, а не через `say`.
        # Владельца события здесь не сверяем, и это решение, а не
        # недосмотр (#26). Событие адресуется содержимым: `dedupe_key`
        # у аудио — само содержимое, один на всю базу, иначе два
        # события на один блоб дали бы две цепочки ASR. Значит телефон
        # получает на свой же звонок старое событие со старым
        # `device_id`, и проверка по устройству похоронила бы очередь
        # навсегда: `Core.kt:137` считает 403 терминальным. Содержимое
        # при этом защищено само: `ingest_audio` сверяет хеш (ТЗ §20) и
        # чужие байты не примет.
        row = con.execute("select kind from events where id=?",
                          (eid,)).fetchone()
        if row and not scope_ok(con, dev, row["kind"]):
            return self.отлуп(
                403, "устройству не разрешён вид «%s»" % row["kind"])
        code, out = ingest_audio(con, self.server.root, eid, self.rfile, n)
        if code < 400:
            # отказ уже написал `say`, второй строки быть не должно
            print(log_line("POST", p.path, code), flush=True)
        return self.say(code, out)

    def handle_expect_100(self):
        """Отказать до тела, если клиент спросил разрешения (#73, хвост Т3.3).

        Предел заливок отвечал 503 после того, как телефон выложил мегабайты:
        сервер обязан вычитать тело, иначе клиент видит broken pipe вместо
        кода. Платили оба — телефон трафиком, сервер потоком, занятым на весь
        слив (до СЛИВ = 8 МиБ). `Expect: 100-continue` снимает обе платы:
        клиент шлёт заголовки и ждёт, мы отказываем до первого байта.

        Место здесь **не занимается** нарочно. Между нашим `100` и телом
        проходит время, и занятое тут место пришлось бы возвращать в пути, где
        тела может не случиться вовсе. Гонка от этого остаётся: место может
        уйти между разрешением и `do_POST`, и тогда 503 придёт по-старому,
        после тела. Это ровно сегодняшнее поведение, то есть ухудшения нет —
        есть выигрыш там, где устройство занято уже на момент вопроса, а это
        и есть частый случай: четвёртая работа в очереди спрашивает, когда
        три предыдущие ещё льют.
        """
        p = urllib.parse.urlparse(self.path)
        if self.command != "POST" or p.path != "/v1/ingest/audio":
            return super().handle_expect_100()
        self.ожидает_тела = True
        try:
            if not self.authed(p.path):
                return False
            n = длина(self)
            if n is not None and n > MAX_BODY:
                self.отлуп(413, "тело больше %d МиБ" % (MAX_BODY >> 20))
                return False
            dev = device_of(self.con(), self.headers.get("Authorization"))
            with _замок:
                занято = _заливки.get(dev, 0) >= ЗАЛИВОК
            if занято:
                self.отлуп(503, "устройство уже льёт %d записей" % ЗАЛИВОК,
                           {"Retry-After": "60"})
                return False
        finally:
            self.ожидает_тела = False
        return super().handle_expect_100()

    def do_POST(self):
        p = urllib.parse.urlparse(self.path)
        if not self.authed(p.path):
            return
        n = длина(self)
        if n is None:
            # границу тела мы не знаем: сливать нечего, а соединение дальше
            # использовать нельзя — хвост уехал бы в следующий запрос
            self.close_connection = True
            return self.say(400, {"error": "нужен числовой Content-Length"},
                            closing=True)
        con = self.con()
        if p.path == "/v1/ingest/audio":
            if n > MAX_BODY:
                return self.отлуп(413, "тело больше %d МиБ" % (MAX_BODY >> 20))
            # Место занимаем после 413: тот отказ диска и потока не держит.
            dev = device_of(con, self.headers.get("Authorization"))
            if not место_под_заливку(dev):
                # 503, а не 429, и это не вкусовщина. `JobFlow.next`
                # (`Core.kt:136-146`) продолжает работу на `code == 0 or
                # >= 500`; свои ветки есть у 200 и 409, а всё остальное —
                # 429 в том числе — уходит в `else -> FAILED`, терминально,
                # и запись пропадает совсем. 429 «слишком много» стоил бы
                # владельцу самого звонка ровно тогда, когда телефон спешит.
                # `Retry-After` отдаём для симметрии с путём 401, но телефон
                # его не читает вовсе, и отката по нему нет: `doWork` не
                # возвращает `Result.retry()` ни на одном пути, так что
                # `setBackoffCriteria` не срабатывает никогда. Повтор держат
                # периодика раз в 15 минут (`Sync.kt:143-145`) и `kick`.
                return self.отлуп(503, "устройство уже льёт %d записей"
                                  % ЗАЛИВОК, {"Retry-After": "60"})
            try:
                return self.аудио(con, p, n, dev)
            except ТаймаутТела as беда:
                # Единственное место, где зависшая заливка ещё видна: выше по
                # стеку `handle_one_request` поймает таймаут сам и молча
                # закроет соединение. Ловим вокруг тела, а не на весь запрос:
                # таймаут на пустом keep-alive соединении штатен и строки не
                # заслуживает — иначе каждая успешная заливка через минуту
                # рожала бы «обрыв» на здоровой связи. И не всякий таймаут из
                # `аудио`, а только рождённый на чтении: `TimeoutError` из
                # записи блоба — поломка склада, и выдавать её за ушедшего
                # клиента значит соврать в диагнозе (нашёл Codex, круг 2).
                # Имя печатаем исходное: обёртка нужна была лишь для отбора.
                print(обрыв(беда.__cause__, self.client_address[0]), flush=True)
                raise                        # соединение закрывает базовый класс
            finally:
                # finally, а не возврат по месту: глобального `try` вокруг
                # `do_POST` нет, необработанное исключение уходит в
                # `handle_error` — и место утекало бы навсегда.
                место_освободить(dev)

        if n > MAX_JSON:
            return self.отлуп(413, "тело больше %d МиБ" % (MAX_JSON >> 20))
        try:
            raw = self.rfile.read(n) if n else b""
        except (TimeoutError, socket.timeout) as беда:
            print(обрыв(беда, self.client_address[0]), flush=True)
            raise
        try:
            data = json.loads(raw or b"{}")
        except ValueError:
            return self.say(400, {"error": "не json"})
        if not isinstance(data, dict):
            # `5` и `[]` — валидный json, но дальше по коду сплошь data.get,
            # и обработчик падал без ответа
            return self.say(400, {"error": "не json"})
        if p.path == ПУТЬ_СЕРДЦА:
            dev = device_of(con, self.headers.get("Authorization"))
            узел = узел_устройства(con, dev)
            if узел is None or not scope_ok(con, dev, "heartbeat"):
                # отозван между `authed` и этой строкой, или allowlist узла
                # сняли руками (`--allow`)
                return self.say(403, {"error": "токен узла отозван или без heartbeat"})
            сердце, беда = разобрать_сердцебиение(data)
            if беда:
                return self.say(400, {"error": беда})
            if not принять_сердцебиение(con, узел, сердце):
                return self.say(409, {"error": "в compute_nodes узел «%s» записан под "
                                               "другим id" % узел})
            return self.say(200, {"node": узел, "interval_s": сердце["interval_s"]})
        if p.path == ПУТЬ_ЗДОРОВЬЯ:
            dev = device_of(con, self.headers.get("Authorization"))
            # Здоровье захвата шлёт тот, кто сдаёт звонки: токену с allowlist
            # без `call` (у плагина Hermes — только `correction`, у узла —
            # `heartbeat`) тревог заводить нельзя (ADR-0009, ревью Т4.3, P2-5)
            if not dev or not scope_ok(con, dev, "call"):
                return self.say(403, {"error": "устройству не разрешён вид «call»"})
            здоровье, беда = разобрать_здоровье(data)
            if беда:
                return self.say(400, {"error": беда})
            if not принять_здоровье(con, dev, здоровье):
                return self.say(200, {"ok": True, "stale": True})
            return self.say(200, {"ok": True})
        if p.path in ("/v1/ingest/event", "/v1/ingest/message", "/v1/ingest/email"):
            kind = {"/v1/ingest/message": "message",
                    "/v1/ingest/email": "email"}.get(p.path) or data.get("kind") or "event"
            беда = плохой_вид(kind)
            if беда:
                # Без этой проверки вид ложился в `events.kind` как есть, и
                # `--allow <id> @history` потом падал навсегда: он собирает
                # список из истории, а `set_scopes` такой вид не принимает —
                # не записывается ничего, включая настоящие виды (#29).
                return self.say(400, {"error": беда}, поля=data)
            if kind in ПСЕВДОВИДЫ:
                # иначе право в списке открывало бы и запись событий такого
                # вида, а `@history` превращал бы её обратно в право
                return self.say(400, {"error": "«%s» — право, а не вид события"
                                               % kind}, поля=data)
            data["kind"] = kind
            data["device_id"] = device_of(con, self.headers.get("Authorization"))
            # Ключ дедупа считает сервер по полям самого события. Присланный
            # ключ позволял завести строку `blob:<sha>` вообще без `blob`, и
            # тогда настоящий звонок с тем же хешем дедуплицировался в неё, а
            # дозагрузка отвечала «событие без аудио» (400) — терминально для
            # клиента. Из своих полей такая строка получиться не может.
            data.pop("dedupe_key", None)
            blob = data.get("blob") or {}
