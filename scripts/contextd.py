    pack_age, pack_bytes = pack_stat(vault)
    # Снимок под замком: словарь правят рабочие потоки, а мы его обходим.
    with _замок:
        отказы = sorted(_отказы.items())
        заперто = sorted(_заперто.items())
        упало = _упало["http"]
        сорвалось = _сорвалось["tls"]
        открытым = sorted(_открытым.items())
    # mara_mobile_* берёт любое устройство, и Gmail-крон раз в 10 минут его
    # всегда «освежит» — телефон виден только поимённо.
    #
    # Поимённо — по имени, а не по строке таблицы: `pair` не запрещает второе
    # устройство с тем же именем (перевыпуск токена так и делается), а две
    # строки с одинаковым набором меток это не шум, а сломанная экспозиция:
    # скрейп её либо отвергает, либо молча берёт одну из строк. Свежесть берём
    # самую новую: имя молчит ровно тогда, когда молчат все его устройства.
    # Самую новую по времени: `max()` по строке врёт после смены пояса, а
    # голый `last_seen` рядом с `max()` SQLite берёт из той же строки, где
    # максимум.
    # любая причина `node_…:<узел>`: молчит, на паузе, без нужной возможности
    ждут = dict(con.execute(
        "select substr(queued_reason, instr(queued_reason, ':') + 1), count(*) from jobs "
        "where state='ready' and queued_reason like 'node\\_%:%' escape '\\' group by 1"))
