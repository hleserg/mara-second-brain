def blob_row(con, sha256):
    """Что база знает о блобе. Спрашиваем её, а не файловую систему: путь
    считается от даты загрузки, поэтому августовская запись, долитая в
    сентябре, по вычисленному сегодня пути не находится (N5)."""
    if not sha256:
        return None
    return con.execute("select path, bytes, purged_at from blobs where sha256=?",
                       (sha256,)).fetchone()


def finish_stored(con, root, event_id):
    """Довести событие с уже лежащим блобом до `stored`: манифест и работа ASR.
    Идемпотентно — второй вызов не заводит вторую работу. Нужно потому, что
    между записью блоба и переводом события демон может умереть.

    Принимаются `new`, `stale` и `quarantined`: событие, брошенное на
    несошедшемся хеше, ещё может дойти — если файл не менялся, телефон
    пересчитает тот же sha и попадёт по дедупу в эту же строку.

    `quarantined` в этом списке — не запас на будущее, а единственный выход из
    карантина. Путь туда штатный и прописан самим ТЗ: нюх не узнал вид (§6.2),
    415 у телефона терминален (`android/.../Core.kt:280`), владелец расширяет
    нюх, `Store.kt:207 retryFailed()` поднимает работу заново — и тогда
    содержимое приходит второй раз и принимается. Без `quarantined` здесь
    событие после такой починки получало 200, блоб ложился в `calls/`, а
    состояние оставалось карантинным: манифеста нет, работы `asr` нет,
    расшифровки не будет никогда. Молчали при этом **все** проверки сверки
    (`запись_без_расшифровки` требует `stored|new|stale`, `блоб_без_манифеста`
    докладывает только файлы, не знакомые базе, `запись_не_долита` исключает
    `quarantined` явно), а находка `карантин` гасла ровно тем действием, о
    котором просит, — уборкой каталога. Перевод состояния — одним
    `update ... where state in (...)`, а не проверкой и записью по отдельности:
    обработчики живут в разных потоках со своими соединениями, и два
    одновременных запроса по одному событию проходили раздельную проверку оба.
    Ценой была вторая цепочка asr→extract→project→digest: час GPU и второй
    дайджест в телеграм. `rowcount` показывает, кто
    успел первым.
    """
    if not con.execute("select 1 from events where id=? and state in "
                       "('new','stale','quarantined')", (event_id,)).fetchone():
        return
    # Манифест — до перехода: файл идемпотентен, а база обязана не говорить
    # «stored» раньше, чем результат лежит на диске (§5.2). Переход и работа
    # — одной транзакцией: смерть демона между ними оставляла звонок, который
    # никто не расшифрует (ADR-0005; `tests/test_reconcile_stored.py`), и
    # лечила его только сверка.
    mi.write_json(mi.manifest_path(root, event_id), manifest(con, root, event_id))
    with транзакция(con):
        if con.execute("update events set state='stored' "
                       "where id=? and state in ('new','stale','quarantined')",
                       (event_id,)).rowcount != 1:
            return
        mi.add_job(con, event_id, "asr")


