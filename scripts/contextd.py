def pair(con, name):
    """Новое устройство. Токен показывается один раз, в базе только sha256.
    Имя с `УЗЕЛ_ПРЕФИКС` — только через `pair_node`: узлом устройство делает
    имя, и обойти проверку имени узла здесь нельзя."""
    if isinstance(name, str) and name.startswith(УЗЕЛ_ПРЕФИКС):
        raise ValueError("узел заводится --pair-node, не --pair")
    return _pair(con, name)


def _pair(con, name):
    token = secrets.token_urlsafe(32)
    dev = "dev_" + secrets.token_hex(8)
    con.execute("insert into devices(id,name,token_sha256,created) values(?,?,?,?)",
                (dev, name, hashlib.sha256(token.encode()).hexdigest(), mi.now_iso()))
    return dev, token


def revoke(con, device_id):
    """Отозвать токен. Последний живой токен телефона уносит и его открытые
    тревоги «записи нет» (Т4.3): закрыть их больше некому, а сверка и
    сводка твердили бы о них неделю (ревью Т4.3, P2-1). Перевыпуск (`--pair`
    того же имени, #47) тревог не трогает — их ведёт новый токен."""
    with транзакция(con):
        con.execute("update devices set revoked_at=? where id=? and revoked_at is null",
                    (mi.now_iso(), device_id))
        row = con.execute("select name from devices where id=?", (device_id,)).fetchone()
        if row and not con.execute("select 1 from devices where name=? and revoked_at is null",
                                   (row["name"],)).fetchone():
            for т in con.execute("select id from alerts where kind=? and object_kind='phone' "
                                 "and object_id=? and state in ('open', 'acked')",
                                 (mi.ЗАПИСИ_НЕТ, row["name"])).fetchall():
                _закрыть_тревогу(con, т["id"], "device_revoked", ("human", "owner"),
                                 row["name"])
    return con.execute("select revoked_at from devices where id=?",
                       (device_id,)).fetchone()


def pair_node(con, узел):
    """Токен узла для сердцебиения (Т7.2): устройство `node:<узел>` с
    allowlist `heartbeat` — событий им не прислать, пакета не прочитать
    (`authed`). Имя узла — как в `ТЯЖЁЛЫЕ` и `compute_nodes.id`; строка
    самого воркера (`ВОРКЕР`) узлом быть не может: его сердцебиение — это
    живость потока воркера для сверки, и чужое писать туда нельзя."""
    if not (isinstance(узел, str) and ВИД.match(узел)):
        raise ValueError("имя узла — строчные латинские, цифры и `_`, с буквы")
    if узел == ВОРКЕР:
        raise ValueError("«%s» — строка воркера doctor, не узел" % ВОРКЕР)
    dev, token = _pair(con, УЗЕЛ_ПРЕФИКС + узел)
    set_scopes(con, dev, ["heartbeat"])
    return dev, token


def узел_устройства(con, device_id):
    """Имя узла, если устройство — узел (`pair_node`), иначе None."""
    row = con.execute("select name from devices where id=?", (device_id,)).fetchone()
    имя = row["name"] if row else None
    return имя[len(УЗЕЛ_ПРЕФИКС):] if имя and имя.startswith(УЗЕЛ_ПРЕФИКС) else None


def device_of(con, header):
    """Устройство по заголовку Authorization или None. Отозванное — тоже None."""
    if not header or not header.startswith("Bearer "):
        return None
    h = hashlib.sha256(header[7:].strip().encode()).hexdigest()
    row = con.execute("select id from devices where token_sha256=? and revoked_at is null",
                      (h,)).fetchone()
    if not row:
        return None
    con.execute("update devices set last_seen=? where id=?", (mi.now_iso(), row["id"]))
    return row["id"]


def scope_ok(con, device_id, kind):
    """Разрешён ли устройству этот вид события (ADR-0009, откат п. 2).

    `scopes is null` означает «как до этой колонки — всё можно», и это не
    временная поблажка, а рабочее состояние: устройство, ещё ничего не
    приславшее, списка не получает, иначе телефон с пустой историей был бы
    отбит на первом же событии. Список заполняется отдельным шагом
    (`--allow`), и только по тому, что устройство реально шлёт.
    """
    if not device_id:
        return False
    row = con.execute("select scopes from devices where id=?", (device_id,)).fetchone()
    if not row:
        # Токен опознан в `authed()`, а строки уже нет — устройство отозвали
        # между двумя запросами к базе. Пропустить значит записать событие с
        # `device_id is null` уже после отзыва; отбить — то, чего отзыв и хотел.
        return False
    if row["scopes"] is None:
        return True
    return kind in row["scopes"].split()


# Т6.3: контракты agent-facing слоя (`docs/contracts/agent-api.md`, фикстур
# `tests/fixtures/agent-contracts.json`). Имена — по образцу ADR-0011
# (`mara.<область>.<имя>.v<N>`), правила версий — его же решение 7: внутри
# версии поля только добавляются, несовместимое — новый суффикс рядом.
