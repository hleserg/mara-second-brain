"""Мелочи, общие для сборщиков карточек (session-note, git-ingest).

Живёт отдельно не ради красоты, а потому что правило «линковать только то, что
есть в реестре» должно быть одно на всех: разъехавшись, две копии тихо начнут
плодить фантомные узлы в графе, и заметит это только линтер §5.6.
"""
import json, os, sys, shlex, fcntl, contextlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from redact import SECRETS          # слой 1 §8.3, чистые регэкспы

def canon_map(vault):
    """Алиас, заголовок или каноническое имя → каноническое (§5.2). Голый
    `[[алиас]]` Obsidian не резолвит — он вставляет `[[Каноническое|алиас]]`, —
    поэтому имя приводим к канону, а незнакомое не линкуем вовсе. Индекса нет
    (клиентский спул) — не линкуем ничего, и это правильно.

    `title` тут наравне с алиасами: имя файла латиницей (`devin`, `sergey`), а в
    тексте сущность зовут заголовком («Devin AI», «Иван Петров»). Без него
    самая очевидная форма имени как раз и не линковалась."""
    try:
        idx = json.load(open(os.path.join(vault or "", "_system/entity-index.json"),
                             encoding="utf-8"))
    except (OSError, ValueError, TypeError):
        return {}
    return {n.lower(): e["canonical"] for e in idx
            for n in [e["canonical"], e.get("title")] + list(e.get("aliases") or []) if n}

def link(name, canon):
    """Значение для frontmatter: ссылка, если сущность известна, иначе текст."""
    c = (canon or {}).get((name or "").lower())
    return "[[%s]]" % c if c else name

def unlink(s):
    """`[[канон|Текст]]` → `Текст`, `[[канон]]` → `канон`. Модель иногда кладёт в
    people уже готовую ссылку — обернуть её второй раз нельзя."""
    s = (s or "").strip()
    if s.startswith("[[") and s.endswith("]]"):
        s = s[2:-2].split("|")[-1].strip()
    return s

def linkify(names, canon):
    """Имена из карточки → `[[канон|как написано]]`; незнакомое остаётся текстом.

    Одна на всех: дистиллятор линкует карточку в момент записи, entity-link
    догоняет старые, когда сущность завелась позже. Разъедься эти двое — часть
    графа была бы связана, часть нет, и по какому принципу — не понял бы никто.
    """
    out = []
    for n in names:
        n = unlink(str(n))
        if not n: continue
        c = (canon or {}).get(n.lower())
        out.append(n if not c else "[[%s]]" % c if c == n else "[[%s|%s]]" % (c, n))
    return out

@contextlib.contextmanager
def locked(vault):
    """Общий с автокоммитом и bisync флок (§13.8). Берём его только вокруг
    записи в волт: качать зеркала под ним — значит держать синк все те минуты,
    что идёт clone."""
    fh = open(os.path.join(vault, ".git/vault-git.lock"), "w")
    try:
        fcntl.flock(fh, fcntl.LOCK_EX)
        yield
    finally:
        fh.close()

def env_file():
    """Где лежит файл с адресами и ключами. MARA_ENV_FILE — чтобы тесты и
    systemd могли увести чтение в сторону от боевого файла."""
    return os.environ.get("MARA_ENV_FILE") or "~/.config/mara/env"


def load_env(path=None):
    """KEY=value из файла в окружение, не затирая уже заданное.

    Адреса машин домашней сети и ключи живут здесь, а не в репозитории: он
    публичный. Уже заданное в окружении (systemd EnvironmentFile, cron) имеет
    приоритет — `setdefault`.

    Тот же файл сорсится шеллом, поэтому разбираем его по-шелловски: `export`
    в начале и хвостовой комментарий шелл срезает, а буквальный разбор оставлял
    бы их внутри значения — в URL это заметят не сразу. Битая строка не
    обрывает файл: ключи после неё нужны не меньше.

    Режет строку `shlex`, а не наши собственные правила. Самодельный разбор
    расходился с шеллом на двух случаях, и оба тихие: `export`, отделённый
    табом, уходил в имя ключа целиком — появлялась переменная
    `export\tMARA_MAC`, а нужной не появлялось вовсе; а срез по ` #` не смотрел
    на кавычки и обрезал `PASS='а # б'` до `а`. Ключ, укоротившийся на середине,
    выглядит как неверный ключ, а не как испорченный файл, — и искать его пойдут
    в облаке, а не здесь.

    Лексим ровно первый токен, а не строку целиком, и комментарии лексеру не
    отдаём вовсе (`commenters = ""`). Оба ограничения куплены кровью:

    * `shlex.split(l)` лексит и хвостовой комментарий. Один апостроф в
      человеческом тексте после значения (`# ноут, ssh-ключ don't touch`) — и
      вся строка уходит в `ValueError`, то есть ключа не появляется вовсе.
      Апостроф в комментарии куда вероятнее решётки в секрете: так чинилка
      оказалась бы опаснее дыры. `shlex.shlex` читает лениво — взяв первый
      токен, до комментария он не доходит.
    * `commenters` по умолчанию `"#"`, и тогда режется `p#ss`, где решётка
      внутри слова. Шелл такое значение хранит целиком, и мы за ним.

    Значение последнего вхождения ключа побеждает: файл сорсится сверху вниз,
    и дописанное в конец переопределение в шелле выигрывает. `setdefault` в
    окружение при этом остаётся — приоритет systemd и крона над файлом другой
    природы, чем приоритет строк внутри файла.
    """
    try:
        with open(os.path.expanduser(path or env_file()), errors="replace") as fh:
            lines = fh.read().splitlines()
    except OSError:
        return
    из_файла = {}
    for l in lines:
        пара = _строка(l)
        if пара:
            из_файла[пара[0]] = пара[1]   # последнее вхождение, как в шелле
    for k, v in из_файла.items():
        os.environ.setdefault(k, v)


def _строка(l):
    """(ключ, значение) или None, если строка ключа не несёт."""
    l = l.strip()
    if not l or l.startswith("#"):
        return None
    лексер = shlex.shlex(l, posix=True)
    лексер.whitespace_split = True
    лексер.commenters = ""
    try:
        токен = лексер.get_token()
        if токен == "export":
            токен = лексер.get_token()
    except ValueError:
        # Незакрытая кавычка или обрыв на слеше — но уже внутри значения, а не
        # в комментарии: до комментария ленивый лексер не дошёл. Шелл такой
        # файл не досорсит целиком; мы теряем одну строку, потому что ключи
        # после неё нужны не меньше, чем до.
        return None
    if not токен or "=" not in токен:
        return None
    k, _, v = токен.partition("=")
    return (k, v) if k else None       # кавычки снял shlex


def нужен_адрес(имя, зачем):
    """Адрес из окружения или внятная смерть вместо тихого промаха мимо порта.

    Файл читаем здесь, а не на импорте модуля: иначе всякий, кто импортирует
    `call_asr`, затягивает в своё окружение и OPENROUTER_API_KEY — тестовому
    процессу он ни к чему.
    """
    v = os.environ.get(имя)
    if not v:
        load_env()
        v = os.environ.get(имя)
    if not v:
        raise SystemExit("не задан %s (%s). Строка `%s=...` кладётся в %s "
                         "(демону — в /etc/mara/contextd.env через systemd)"
                         % (имя, зачем, имя, env_file()))
    return v


def scrub(s):
    """Текст человека уезжает в волт как есть, а волт синкается в R2 и
    коммитится. Ключ, вставленный в реплику или в сообщение коммита, уехал бы
    вместе с ним — §11, «секреты не в волте, никогда»."""
    for rx, repl in SECRETS: s = rx.sub(repl, s)
    return s

def yaml_str(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')
