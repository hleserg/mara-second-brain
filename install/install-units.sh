#!/usr/bin/env bash
# systemd-юниты Мары из репозитория в /etc/systemd/system (issue #89).
#
# До этого скрипта юниты лежали в репозитории готовыми — вместе с системным
# именем пользователя doctor и абсолютным путём до его домашнего каталога.
# Репозиторий публичный, а юнит с зашитым путём не ставится больше никуда:
# переустановка под другим именем означала бы правку файла руками, и разошёлся
# бы он с репозиторием молча. Шаблоны и рендер — тот же приём, что в
# install-cron.sh, и намеренно тот же: две разные механики установки в одном
# каталоге стоили бы дороже, чем одна повторённая.
#
#   install-units.sh            показать расхождение, ничего не менять
#   install-units.sh --apply    поставить и перечитать юниты
#
# Переменные: REPO (куда смотрит юнит), TPL_DIR (откуда взять шаблоны, по
# умолчанию REPO/install), USER_NAME, STATE, VENV_TDLIB, DEST.
#
# Рестарта НЕ делает, и это не забывчивость. Рестарт contextd открывает базу
# реестра, а открытие зовёт `_ужать_ledger()` — перестройку трёх таблиц. Это
# гейт Г4 (`docs/PLAN-to-done.md` §4) и шаг ранбука
# (`docs/RUNBOOK-deploy.md`), то есть решение оператора, а не побочный эффект
# установщика. `daemon-reload` рестартом не является: он перечитывает юниты, а
# живые процессы продолжают работать со старой конфигурацией до рестарта.
set -euo pipefail

REPO="${REPO:-$(cd "$(dirname "$0")/.." && pwd)}"
# Откуда взять шаблоны — отдельно от того, куда будет смотреть юнит. По
# умолчанию это один и тот же checkout, но приёмочная проверка нужна ровно
# обратная: собрать шаблоны из ветки и сверить с юнитом, который смотрит в
# рабочий checkout. То же разделение есть в install-cron.sh (`TPL`).
TPL_DIR="${TPL_DIR:-$REPO/install}"
USER_NAME="${USER_NAME:-$(id -un)}"
STATE="${STATE:-$HOME/.local/state/mara}"
VENV_TDLIB="${VENV_TDLIB:-$HOME/.local/share/mara/venv-tdlib/bin/python}"
DEST="${DEST:-/etc/systemd/system}"
UNITS=(contextd.service tdlib-ingest.service)

рендер() {
  # ${x//&/\\&}: в правой части `s|…|…|` амперсанд означает «весь матч», и путь
  # с ним подставился бы искажённым — молча, в живой юнит. Та же защита стоит в
  # install-cron.sh по той же причине.
  sed -e "s|@USER@|${USER_NAME//&/\\&}|g" \
      -e "s|@REPO@|${REPO//&/\\&}|g" \
      -e "s|@STATE@|${STATE//&/\\&}|g" \
      -e "s|@VENV_TDLIB@|${VENV_TDLIB//&/\\&}|g" \
      "$TPL_DIR/$1.in"
}

# Незаполненная дырка — единственный способ этого скрипта навредить молча.
# systemd не считает `@STATE@` ошибкой: он примет это за относительный путь и
# запустит сервис с `ReadWritePaths`, указывающим не туда. Опечатка в имени
# подстановки (`@VENV@` вместо `@VENV_TDLIB@`) даёт ровно это. Поэтому проверка
# идёт до обоих режимов и отказывает даже в --check: собранный юнит с дыркой не
# с чем сравнивать, его надо починить.
дырки() { рендер "$1" | grep -nE '@[A-Z_]+@' || true; }

mode="${1:---check}"
case "$mode" in
  --check|--apply) ;;
  *) echo "использование: $0 [--check|--apply]" >&2; exit 2 ;;
esac

for u in "${UNITS[@]}"; do
  leftover=$(дырки "$u")
  if [ -n "$leftover" ]; then
    echo "== $u: в собранном юните осталась незаполненная подстановка," \
         "ничего не трогаю:" >&2
    printf '%s\n' "$leftover" | sed 's/^/   /' >&2
    exit 3
  fi
done

if [ "$mode" = --check ]; then
  drift=0
  for u in "${UNITS[@]}"; do
    if [ ! -f "$DEST/$u" ]; then
      echo "== $u в $DEST нет — не установлен"
      drift=1
      continue
    fi
    if diff -u "$DEST/$u" <(рендер "$u"); then
      echo "== $u совпадает с шаблоном"
    else
      echo "== $u расходится с шаблоном (выше: установлено → шаблон)"
      drift=1
    fi
  done
  exit $drift
fi

# Собираем в свой временный файл и только потом ставим: рендерить прямо в
# $DEST нельзя — там нет прав без sudo, а `sudo sh -c 'sed … > файл'` отдал бы
# root'у всю строку целиком.
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
for u in "${UNITS[@]}"; do
  рендер "$u" > "$tmp"
  sudo install -m 0644 -o root -g root "$tmp" "$DEST/$u"
  echo "== $u поставлен"
done
sudo systemctl daemon-reload

# Проверяем не то, что отправили, а то, что systemd принял: `systemctl cat`
# читает юнит его глазами, вместе с drop-in'ами. Комментарии снимаем с обеих
# сторон — `systemctl cat` дописывает своим первую строку с путём файла. Если
# на юните висит drop-in, он проявится здесь расхождением, и это правильно:
# drop-in переопределяет то, что мы только что поставили, и оператор обязан его
# увидеть.
mismatch=0
for u in "${UNITS[@]}"; do
  if diff -u <(systemctl cat "$u" | grep -v '^#') <(рендер "$u" | grep -v '^#'); then
    echo "== $u: systemd видит ровно то, что в шаблоне"
  else
    echo "== $u: systemd видит не то, что мы поставили (см. дифф выше)" >&2
    mismatch=1
  fi
done

echo "== рестарта НЕ делал. Рестарт contextd перестраивает таблицы реестра"
echo "   (_ужать_ledger в mara_ingest.connect) — это гейт Г4 и шаг ранбука."
exit $mismatch
