"""Память contextd на заливке аудио не растёт с телом (Т3б.4; ТЗ §17.3 п.1).

Стенд целиком живёт в `scripts/upload_memory_probe.py`: сервер отдельным
процессом, устройство через `pair()`, валидный WAV кусками, RSS из
`/proc/<pid>/status`. Здесь только два прогона и границы к ним.

Быстрый — восемь мегабайт: профиль на таком теле не виден, зато виден сервер,
который поднял тело в память целиком — его прирост был бы не меньше тела.
Медленный — тело под `MAX_BODY`, и он не только держит прирост под пределом,
но и сравнивает его с приростом на теле в пять раз меньшем: «не линейно»
проверяется разницей, а не одним числом. Гоняется по `MARA_SLOW=1`:
четверть гигабайта на каждый прогон гейта — лишнее, числа лежат в
`docs/upload-memory-profile.md`.
"""
import os, sys, unittest

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import contextd
import upload_memory_probe as проба

МиБ = 1 << 20


@unittest.skipUnless(os.path.exists("/proc/self/status"),
                     "нет /proc — RSS снять нечем")
class Память(unittest.TestCase):
    def принято(self, r):
        self.assertEqual(r["код"], 200, "заливка не принята: %r" % (r["ответ"],))
        self.assertEqual(r["ответ"].get("bytes"), r["байт"],
                         "сервер принял не всё — профиль неполного тела ничего не доказывает")

    def test_маленькое_тело_не_поднимается_в_память_целиком(self):
        r = проба.замер(mib=8, период=0.05)
        self.принято(r)
        self.assertLess(r["прирост"], r["байт"],
                        "RSS вырос на размер тела: сервер буферизует тело целиком")
        self.assertLess(r["прирост"], проба.ПРЕДЕЛ_ПРИРОСТА)

    @unittest.skipUnless(os.environ.get("MARA_SLOW"),
                         "медленный: четверть гигабайта, гоняется по MARA_SLOW=1")
    def test_тело_под_лимитом_не_растит_rss(self):
        # 250, а не 300 из плана: `MAX_BODY` = 256 МиБ, тело больше него уходит
        # в 413 после слива восьми мегабайт, и мерить там нечего.
        большое = min(250, contextd.MAX_BODY // МиБ)
        малое = большое // 5
        м = проба.замер(mib=малое)
        б = проба.замер(mib=большое)
        self.принято(м)
        self.принято(б)
        self.assertLess(б["прирост"], проба.ПРЕДЕЛ_ПРИРОСТА,
                        "прирост %s на теле %d МиБ" % (проба.мб(б["прирост"]), большое))
        # Линейный рост дал бы здесь разницу в четыре малых тела (200 МиБ);
        # восемь мегабайт — четыре процента от неё, и восемь кусков `КУСОК`.
        self.assertLess(б["прирост"] - м["прирост"], 8 * МиБ,
                        "тело в пять раз больше — RSS вырос на %s больше"
                        % проба.мб(б["прирост"] - м["прирост"]))


if __name__ == "__main__":
    unittest.main()
